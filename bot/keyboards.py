from telegram import ReplyKeyboardMarkup, KeyboardButton


# ==========================================================
# دالة عامة لإنشاء لوحة أزرار Telegram
# ==========================================================

def make_keyboard(الصفوف):

    الأزرار = []

    for صف in الصفوف:

        صف_أزرار = []

        for نص in صف:

            صف_أزرار.append(
                KeyboardButton(نص)
            )

        الأزرار.append(صف_أزرار)

    return ReplyKeyboardMarkup(
        الأزرار,
        resize_keyboard=True,
        one_time_keyboard=False,
        is_persistent=True,
    )


# ==========================================================
# الواجهة الرئيسية للمستخدم
# ==========================================================

def user_keyboard(is_admin_user=False):

    الصفوف = [
        ["📖 القرآن والثقافة"],
        ["📚 الملازم"],
        ["🎧 المحاضرات"],
        ["ℹ️ عن البوت"],
    ]

    if is_admin_user:

        الصفوف.append([
            "⚙️ الإدارة"
        ])

    return make_keyboard(الصفوف)


# ==========================================================
# واجهة القوائم للمستخدم
# ==========================================================

def public_menu_keyboard(children, contents=None):

    الصفوف = []

    # ------------------------------------------------------
    # القوائم الفرعية
    # ------------------------------------------------------

    for child in children:

        الصفوف.append([
            f"📂 {child['name']}"
        ])

    # ------------------------------------------------------
    # المحتوى
    # ------------------------------------------------------

    if contents:

        for content in contents:

            icon = content_type_icon(
                content["content_type"]
            )

            الصفوف.append([
                f"{icon} {content['title']}"
            ])

    # ------------------------------------------------------
    # رجوع
    # ------------------------------------------------------

    الصفوف.append([
        "◀️ رجوع"
    ])

    return make_keyboard(الصفوف)


# ==========================================================
# أيقونة نوع المحتوى
# ==========================================================

def content_type_icon(content_type):

    icons = {

        "text": "📝",

        "document": "📄",

        "photo": "🖼️",

        "video": "🎬",

        "audio": "🎧",

        "voice": "🎤",

        "url": "🔗",
    }

    return icons.get(
        content_type,
        "📄"
    )


