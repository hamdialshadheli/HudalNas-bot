from telegram import ReplyKeyboardMarkup, KeyboardButton


# ==========================================================
# دالة عامة لإنشاء لوحة أزرار Telegram
# ==========================================================

def make_keyboard(الصفوف):

    الأزرار = []

    for صف in الصفوف:

        صف_أزرار = []

        for نص in صف:
            صف_أزرار.append(
                KeyboardButton(نص)
            )

        الأزرار.append(صف_أزرار)

    return ReplyKeyboardMarkup(
        الأزرار,
        resize_keyboard=True,
        one_time_keyboard=False,
        is_persistent=True,
    )


# ==========================================================
# واجهة المستخدم الرئيسية
# ==========================================================

def user_keyboard(is_admin_user=False):

    الصفوف = [
        ["📖 القرآن والثقافة"],
        ["📚 الملازم"],
        ["🎧 المحاضرات"],
        ["ℹ️ عن البوت"],
    ]

    if is_admin_user:
        الصفوف.append(
            ["⚙️ الإدارة"]
        )

    return make_keyboard(الصفوف)


# ==========================================================
# واجهة المشرف
# ==========================================================

def admin_keyboard():

    return make_keyboard([
        ["📂 إدارة القوائم"],
        ["➕ إضافة محتوى", "✏️ تعديل المحتوى"],
        ["🗑️ حذف المحتوى", "↕️ ترتيب العناصر"],
        ["👥 المشرفون", "📊 الإحصائيات"],
        ["👤 واجهة المستخدم"],
    ])


# ==========================================================
# إدارة القوائم الرئيسية
# ==========================================================

def menus_keyboard(menus):

    الصفوف = []

    for menu in menus:

        الصفوف.append([
            f"📂 {menu['name']}"
        ])

    الصفوف.append([
        "➕ إنشاء قائمة رئيسية"
    ])

    الصفوف.append([
        "◀️ رجوع"
    ])

    return make_keyboard(الصفوف)


# ==========================================================
# أزرار داخل القائمة
# ==========================================================

def menu_management_keyboard(children):

    الصفوف = []

    for child in children:

        الصفوف.append([
            f"📂 {child['name']}"
        ])

    الصفوف.append([
        "➕ إنشاء قائمة فرعية"
    ])

    الصفوف.append([
        "◀️ رجوع"
    ])

    return make_keyboard(الصفوف)


# ==========================================================
# زر الرجوع
# ==========================================================

def back_keyboard():

    return make_keyboard([
        ["◀️ رجوع"]
    ])


# ==========================================================
# زر الإلغاء
# ==========================================================

def cancel_keyboard():

    return make_keyboard([
        ["❌ إلغاء"]
    ])
