from telegram import ReplyKeyboardMarkup, KeyboardButton


# ==========================================================
# دالة عامة لإنشاء لوحة أزرار Telegram
# ==========================================================

def make_keyboard(rows):

    buttons = []

    for row in rows:

        buttons.append([
            KeyboardButton(text)
            for text in row
        ])

    return ReplyKeyboardMarkup(
        buttons,
        resize_keyboard=True,
        one_time_keyboard=False,
        is_persistent=True,
    )


# ==========================================================
# الواجهة الرئيسية للمستخدم
# ==========================================================

def user_keyboard(is_admin_user=False):

    rows = [
        ["📖 القرآن والثقافة"],
        ["📚 الملازم"],
        ["🎧 المحاضرات"],
        ["ℹ️ عن البوت"],
    ]

    if is_admin_user:

        rows.append([
            "⚙️ الإدارة"
        ])

    return make_keyboard(rows)


# ==========================================================
# واجهة القوائم العامة للمستخدم
# ==========================================================

def public_menu_keyboard(children, contents=None):

    rows = []

    # ------------------------------------------------------
    # القوائم الفرعية
    # ------------------------------------------------------

    for child in children:

        rows.append([
            f"📂 {child['name']}"
        ])

    # ------------------------------------------------------
    # المحتوى
    # ------------------------------------------------------

    if contents:

        for content in contents:

            icon = content_type_icon(
                content["content_type"]
            )

            rows.append([
                f"{icon} {content['title']}"
            ])

    # ------------------------------------------------------
    # الرجوع
    # ------------------------------------------------------

    rows.append([
        "◀️ رجوع"
    ])

    return make_keyboard(rows)


# ==========================================================
# أيقونة نوع المحتوى
# ==========================================================

def content_type_icon(content_type):

    icons = {

        "text": "📝",

        "document": "📄",

        "photo": "🖼️",

        "video": "🎬",

        "audio": "🎧",

        "voice": "🎤",

        "url": "🔗",
    }

    return icons.get(
        content_type,
        "📄"
    )


